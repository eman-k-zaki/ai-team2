# Cell 3: Padding & Truncation (Token Sequences)
def pad_or_truncate(tokens, max_len=7, pad_token="<PAD>"):
    if len(tokens) > max_len:
        # Truncation
        return tokens[:max_len]
    else:
        # Padding
        return tokens + [pad_token] * (max_len - len(tokens))

