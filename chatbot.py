# Cell 2: NLP Preprocessing & Cleaning Pipeline (Updated Downloads)
import re
import nltk
from nltk.corpus import stopwords
from nltk.stem import PorterStemmer, WordNetLemmatizer
import spacy

# تحميل الموارد المطلوبة من NLTK بما فيها punkt_tab
nltk.download('punkt', quiet=True)
nltk.download('punkt_tab', quiet=True)
nltk.download('stopwords', quiet=True)
nltk.download('wordnet', quiet=True)
nltk.download('omw-1.4', quiet=True)

nlp = spacy.load("en_core_web_sm")
stemmer = PorterStemmer()
lemmatizer = WordNetLemmatizer()
stop_words = set(stopwords.words('english'))

def clean_and_preprocess(raw_text):
    print("--- Original Text ---")
    print(raw_text)

    # 1. Lowercasing
    text = raw_text.lower()

    # 2. Remove HTML Tags & URLs
    text = re.sub(r'<.*?>', '', text)
    text = re.sub(r'https?://\S+|www\.\S+', '', text)

    # 3. Remove Punctuation & Special Characters / Numbers
    text = re.sub(r'[^a-zA-Z\s]', '', text)
    text = re.sub(r'\s+', ' ', text).strip()

    # 4. Tokenization (Word-level)
    tokens = nltk.word_tokenize(text)

    # 5. Stopwords Removal
    filtered_tokens = [w for w in tokens if w not in stop_words]

    # 6. Stemming vs. Lemmatization
    stemmed = [stemmer.stem(w) for w in filtered_tokens]
    lemmatized = [lemmatizer.lemmatize(w) for w in filtered_tokens]

    return {
        "cleaned_tokens": filtered_tokens,
        "stemmed": stemmed,
        "lemmatized": lemmatized
    }

# تجربة دالة التنظيف
